def aliases_for(make, model):
    aliases = set(MAKE_ALIASES.get(make, []))
    name = model.lower()
    for needles, values in ALIAS_RULES:
        if any(needle in name for needle in needles):
            aliases.update(values)
    return sorted(aliases)


